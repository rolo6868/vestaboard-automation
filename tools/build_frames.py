def main():
    for name, (style, lines) in FRAMES.items():
        inner = COLS - 2 * len(STYLES[style]["side"][:1])
        for ln in lines:
            if len(ln) > inner:
                sys.exit(f"{name}: '{ln}' is {len(ln)} chars, style {style} fits {inner}")
        src = bordered(lines, ROWS, COLS, **STYLES[style])
        (OUT / f"{name}.txt").write_text(f"# generated by tools/build_frames.py ({style})\n{src}\n", encoding="utf-8")
    print(f"wrote {len(FRAMES)} frames")


if __name__ == "__main__":
    main()
